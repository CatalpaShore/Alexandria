function getActorNameVariants(actorZh) {
  const normalized = normalizeText(actorZh);
  if (!normalized) return [];

  const variants = new Set([normalized]);
  const withoutParenthetical = normalized.replace(/[（(][^）)]+[）)]/g, "").trim();
  if (withoutParenthetical) variants.add(withoutParenthetical);

  for (const match of normalized.matchAll(/[（(]([^）)]+)[）)]/g)) {
    for (const part of match[1].split(/[、,，/]/)) {
      const cleaned = normalizeText(part).replace(/饰$/u, "").trim();
      if (cleaned) variants.add(cleaned);
    }
  }

  return [...variants].sort((a, b) => b.length - a.length);
}

function stripRomanizedAliasesNextToActorNames(translated, actorsZh) {
  let output = normalizeText(translated);
  for (const actorZh of actorsZh.flatMap(getActorNameVariants)) {
    const escaped = actorZh.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    output = output.replace(new RegExp(`\\b([A-Z][a-z]{2,})\\s+${escaped}`, "g"), (match, token) => {
      return ROMANIZED_ALIAS_TOKEN_EXCLUSIONS.has(token) ? match : actorZh;
    });
    output = output.replace(
      new RegExp(`${escaped}\\s+[（(][A-Z][a-z]{2,}(?:[\\s-]+[A-Z][a-z]{2,}){0,2}[）)]`, "g"),
      actorZh
    );
  }
  return cleanText(output);
}

function trimDuplicateTrailingActorNames(translated, actorsZh) {
  let output = normalizeText(translated);
  const actorNames = actorsZh.map(normalizeText).filter(Boolean);
  let changed = true;

  while (changed) {
    changed = false;
    for (const actorZh of actorNames) {
      const escaped = actorZh.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const matches = [...output.matchAll(new RegExp(escaped, "g"))];
      if (matches.length < 2) continue;
      const next = output.replace(new RegExp(`[\\s、，,。；;：:~～-]*${escaped}[。.!！?？]*$`, "g"), "");
      if (next === output) continue;
      output = next;
      changed = true;
    }
  }

  return cleanText(output);
}

function improveNarrativeText(source, translated, metadata, field = "narrative") {
  let output = improveTranslatedText(source, translated, "narrative");
  for (const [index, previousActor] of (metadata.previousActorsZh ?? []).entries()) {
    const previous = normalizeText(previousActor);
    const current = normalizeText(metadata.actorsZh[index]);
    if (previous && current && previous !== current) output = output.split(previous).join(current);
  }
  if (field === "title") {
    output = repairMediaTitleTerms(source, output);
  }
  output = alignTextWithActors(source, output, metadata.actors, metadata.actorsZh);
  output = applyGenreAwareNarrativeReplacements(source, output, metadata.genres, metadata.genresZh);
  output = alignTextWithActors(source, output, metadata.actors, metadata.actorsZh);
  output = appendMissingTrailingActors(source, output, metadata.actors, metadata.actorsZh);
  output = stripRomanizedAliasesNextToActorNames(output, metadata.actorsZh);
  output = dedupeAdjacentActorNames(output, metadata.actorsZh);
  output = trimDuplicateTrailingActorNames(output, metadata.actorsZh);
  return cleanText(output);
}

function looksLikeBrand(value) {
  return /^[A-Za-z0-9][A-Za-z0-9\s._:/+()[\],&'"!-]*$/.test(value);
}

export function getKnownTermTranslation(source, context = "generic") {
  const normalized = normalizeText(source);
  if (!normalized) return "";

  if (context === "genre" && GENRE_TERMS.has(normalized)) return GENRE_TERMS.get(normalized);
  if (context === "series" && SERIES_TERMS.has(normalized)) return SERIES_TERMS.get(normalized);
  if (["maker", "label", "series"].includes(context) && MAKER_TERMS.has(normalized)) {
    return MAKER_TERMS.get(normalized);
  }
  if (context === "actor" && ACTOR_TERMS.has(normalized)) return ACTOR_TERMS.get(normalized);
  if (context === "director" && DIRECTOR_TERMS.has(normalized)) return DIRECTOR_TERMS.get(normalized);
  if (GENERIC_TERMS.has(normalized)) return GENERIC_TERMS.get(normalized);

  if (["maker", "label", "series"].includes(context) && looksLikeBrand(normalized)) {
    return normalized;
  }

  return "";
}

export function improveTranslatedText(source, translated, context = "generic") {
  const sourceText = normalizeText(source);
  const known = getKnownTermTranslation(sourceText, context);
  if (known) return known;

  const translatedText = normalizeText(translated);
  if (!translatedText) return translatedText;

  let output = applyTextReplacements(translatedText);
  output = applySourceAwareReplacements(sourceText, output);

  if (context === "genre") {
    output = output.replace(/^高视力$/, "高清");
  }

  if (["maker", "label", "series"].includes(context) && looksLikeBrand(sourceText)) {
    return sourceText;
  }

  return output;
}

export function improveTranslatedArray(sources, translations, context) {
  return sources.map((source, index) => improveTranslatedText(source, translations[index] ?? "", context));
}

export function improveMetadataTranslation(input, translated) {
  const actorsZh = improveTranslatedArray(input.actors, translated.actorsZh, "actor");
  const genresZh = improveTranslatedArray(input.genres, translated.genresZh, "genre");
  const narrativeMetadata = {
    actors: input.actors,
    actorsZh,
    previousActorsZh: translated.actorsZh,
    genres: input.genres,
    genresZh
  };

  return {
    titleZh: improveNarrativeText(input.title, translated.titleZh, narrativeMetadata, "title"),
    summaryZh: improveNarrativeText(input.summary, translated.summaryZh, narrativeMetadata),
    directorZh: improveTranslatedText(input.director, translated.directorZh, "director"),
    actorsZh,
    genresZh,
    makerZh: improveTranslatedText(input.maker, translated.makerZh, "maker"),
    labelZh: improveTranslatedText(input.label, translated.labelZh, "label"),
    seriesZh: improveTranslatedText(input.series, translated.seriesZh, "series")
  };
}
