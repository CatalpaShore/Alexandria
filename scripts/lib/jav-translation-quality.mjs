function shouldApplyActorTermToText(source) {
  if (NARRATIVE_ACTOR_TERM_EXCLUSIONS.has(source)) return false;
  if (!/[A-Za-z]/.test(source)) return false;
  const target = ACTOR_TERMS.get(source) ?? "";
  if (!/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(target)) return false;
  if (source.includes(" ")) return source.length >= 6;
  if (source === source.toUpperCase()) return source.length >= 4;
  return source.length >= 5;
}

function applyActorTermReplacements(value) {
  let output = value;
  const entries = [...ACTOR_TERMS.entries()]
    .filter(([from]) => shouldApplyActorTermToText(from))
    .sort((a, b) => b[0].length - a[0].length);

  for (const [from, to] of entries) {
    const flags = from === from.toUpperCase() ? "g" : "gi";
    const pattern = new RegExp(`(^|[^A-Za-z])${escapeRegExp(from)}(?=$|[^A-Za-z])`, flags);
    output = output.replace(pattern, `$1${to}`);
  }

  return output;
}

function applyTextReplacements(value) {
  let output = value;
  for (const [from, to] of TEXT_REPLACEMENTS) {
    output = output.split(from).join(to);
  }
  output = applyActorTermReplacements(output);
  for (const [from, to] of ADULT_TERM_REGEX_REPLACEMENTS) {
    output = output.replace(from, to);
  }
  for (const [from, to] of POST_TEXT_REPLACEMENTS) {
    output = output.split(from).join(to);
  }
  return cleanText(output);
}

function applySourceAwareReplacements(source, translated) {
  let output = translated;
  for (const rule of SOURCE_AWARE_REPLACEMENTS) {
    if (!rule.source.test(source)) continue;
    for (const [from, to] of rule.replacements) {
      output = output.replace(from, to);
    }
  }
  return cleanText(output);
}

function repairMediaTitleTerms(source, translated) {
  let output = normalizeText(translated);
  const sourceText = normalizeText(source);
  if (!sourceText || !output) return output;

  const hasTitleCountContext = /(?:\d+\s*タイトル|全タイトル|Titles?\b|Exclusive Title)/i.test(sourceText);
  if (hasTitleCountContext) {
    output = output
      .replace(/第([一二三四五六七八九十\d]+)\s*个独家标题/g, "第$1部独家作品")
      .replace(/(\d+)\s*个?\s*标题/g, "$1 部作品")
      .replace(/(\d+)\s*首(?=\s*(?:\d+\s*小时|小时|特别|特辑|$))/g, "$1 部作品")
      .replace(/全标题/g, "全作品")
      .replace(/所有标题/g, "所有作品")
      .replace(/独家标题/g, "独家作品");
  }

  const hasSegmentContext = /(?:コーナー|Segments?\b|Scenes?\b)/i.test(sourceText);
  if (hasSegmentContext) {
    output = output
      .replace(/(\d+)\s*个?\s*角(?:落|题)?/g, "$1 段内容")
      .replace(/全(\d+)\s*角/g, "全$1 段内容")
      .replace(/(\d+)\s*个?\s*部分/g, "$1 段内容")
      .replace(/第(\d+)\s+段内容/g, "第$1段内容")
      .replace(/角题/g, "片段")
      .replace(/角落/g, "片段");
  }

  output = output
    .replace(/(\d+)\s+部作品/g, "$1部作品")
    .replace(/(\d+)\s+段内容/g, "$1段内容");

  if (/题材$/.test(output)) {
    output = output.replace(/题材$/, "题材作品");
  }

  if (/标题$/.test(output)) {
    output = output.replace(/标题$/, "作品");
  }

  return cleanText(output);
}

function sourceStartsWithTerm(source, term) {
  return normalizeText(source).startsWith(normalizeText(term));
}

function sourceEndsWithTerm(source, term) {
  return normalizeText(source).endsWith(normalizeText(term));
}

function replaceLeadingName(value, actorZh) {
  let output = normalizeText(value);
  if (!output || output.includes(actorZh)) return output;

  output = output.replace(/^[A-Z][A-Za-z]+(?:[ .'-]+[A-Z][A-Za-z]+){0,3}(?=[\s，,。！!？?:：、~～-]|$)/, actorZh);
  if (output.includes(actorZh)) return cleanText(output);

  output = output.replace(/^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}·]{2,10}(?=[\s，,。！!？?:：、~～-]|$)/u, actorZh);
  if (output.includes(actorZh)) return cleanText(output);

  const leading = output.match(/^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}·]{2,10}/u)?.[0] ?? "";
  if (leading && output.length > leading.length + 2) {
    const replaceLength = Math.min(leading.length, Math.max(2, actorZh.length));
    return cleanText(`${actorZh}${output.slice(replaceLength)}`);
  }

  return cleanText(output);
}

function replaceTrailingName(value, actorZh) {
  let output = normalizeText(value);
  if (!output || output.includes(actorZh)) return output;

  output = output.replace(/(?:\s+|^)[A-Z][A-Za-z]+(?:[ .'-]+[A-Z][A-Za-z]+){0,3}$/u, (match) => {
    return match.startsWith(" ") ? ` ${actorZh}` : actorZh;
  });
  if (output.includes(actorZh)) return cleanText(output);

  output = output.replace(
    /([\s，,。！!？?:：、~～-]+)([\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}·]{2,10})$/u,
    (match, separator, name, offset, text) => {
      const previous = text[offset - 1] ?? "";
      if (/\d/.test(previous) || /^(万次下载|次下载|下载|分钟|小时|日元)$/.test(name)) return match;
      return `${separator}${actorZh}`;
    }
  );
  if (output.includes(actorZh)) return cleanText(output);

  const trailing = output.match(/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}·]{2,10}$/u)?.[0] ?? "";
  if (trailing && output.length > trailing.length + 2) {
    return cleanText(`${output} ${actorZh}`);
  }

  return cleanText(output);
}

function alignTextWithActors(source, translated, actors, actorsZh) {
  let output = normalizeText(translated);
  const sourceText = normalizeText(source);
  if (!sourceText || !output) return output;

  for (const [index, actor] of actors.entries()) {
    const actorSource = normalizeText(actor);
    const actorTarget = normalizeText(actorsZh[index]);
    if (!actorSource || !actorTarget || !sourceText.includes(actorSource) || output.includes(actorTarget)) continue;

    if (sourceStartsWithTerm(sourceText, actorSource)) {
      output = replaceLeadingName(output, actorTarget);
    } else if (sourceEndsWithTerm(sourceText, actorSource)) {
      output = replaceTrailingName(output, actorTarget);
    } else {
      output = output.split(actorSource).join(actorTarget);
    }
  }

  return cleanText(output);
}

function isDescriptiveActorField(actorSource, actorTarget) {
  const sourceText = normalizeText(actorSource);
  const targetText = normalizeText(actorTarget);
  if (sourceText.length > 18 || targetText.length > 18) return true;
  return /歳|才|さん|ちゃん|先輩|後輩|店員|妻|奥様|モデル|GAL|ギャル|嬢|\/|！！|[0-9]{2}/.test(
    `${sourceText} ${targetText}`
  );
}

function appendMissingTrailingActors(source, translated, actors, actorsZh) {
  let output = normalizeText(translated);
  const sourceText = normalizeText(source);
  if (!sourceText || !output) return output;

  const sourceTail = sourceText.slice(-480);
  const missing = [];

  for (const [index, actor] of actors.entries()) {
    const actorSource = normalizeText(actor);
    const actorTarget = normalizeText(actorsZh[index]);
    if (!actorSource || !actorTarget || output.includes(actorTarget)) continue;
    if (isDescriptiveActorField(actorSource, actorTarget)) continue;
    if (!sourceTail.includes(actorSource)) continue;
    missing.push(actorTarget);
  }

  if (missing.length === 0) return cleanText(output);
  return cleanText(`${output} ${missing.join(" ")}`);
}

